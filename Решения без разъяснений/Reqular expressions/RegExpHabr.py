'''
Задача 12. Близкие слова

Для простоты будем считать словом любую последовательность букв, цифр и знаков _ (то 
есть символов \w). Дан текст. Необходимо найти в нём любой фрагмент, где сначала идёт 
слово «олень», затем не более 5 слов, и после этого идёт слово «заяц».
'''
def pract12(string):
    try:
        return re.search(r'\bолень\b(?:\s*\W*\w+\W*\s*){,5}\bзаяц\b', string)[0]
    except:
        return 'Нет'
