'''
Задача 10. CamelCase -> under_score

Владимир написал свой открытый проект, именуя переменные в стиле «ВерблюжийРегистр».
И только после того, как написал о нём статью, он узнал, что в питоне для имён 
переменных принято использовать подчёркивания для разделения слов (under_score). 
Нужно срочно всё исправить, пока его не «закидали тапками».

Задача могла бы оказаться достаточно сложной, но, к счастью, Владимир совсем не 
использовал строковых констант и классов. Поэтому любая последовательность букв и 
цифр, внутри которой есть заглавные, — это имя переменной, которое нужно поправить.
'''
def pract10(string):
    def repl(march):
        if march.start() - 1 == -1 or string[march.start()-1] == ' ':
            return march[0].lower()
        else:
            return '_' + march[0].lower()
    return re.sub(r'[A-Z][a-z]+\d*', repl, string)
