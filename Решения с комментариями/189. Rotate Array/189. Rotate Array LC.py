'''
Поскольку количество шагов k может быть больше длины массива, просто взять
кусок массива и переставить его в начало не выйдет. А алгоритм, который будет
переставлять по одному элементу за каждый шаг, очевидно будет слишком тяжёлым,
так как при переставлении элемента с конца в начало меняются индексы всех 
элементов массива, и переставлять каждый из 100000 элементов в nums на 
каждом из 100000 шагов k (максимальные значения тестов по условию задачи) 
приведёт к исполнению компьютером колоссальных десяти миллиардов операций,
которые, конечно же, будут исполняться несколько минут. Так что же остаётся?

На самом деле первое, что я понял: переставление элементов на k шагов равных 
длине массива - это в результате ровно тот же массив, с тем же порядком 
элементов. И что это значит? А это значит, что из числа k можно вычитать длину
массива до тех пор, пока k не станет меньше длины массива nums. И вот этот
остаток в k является финальной перестановкой, которая и приводит к конечному 
результату, а все остальные перестановки, которые мы вычли - фактически, никак 
не изменяют массив, поэтому такие перестановки не нужны. То есть, по итогу, 
достаточно просто уменьшить большое значение k до его отстатка от деления на 
длину массива nums, чтобы получить только то количество шагов, которые и меняют
в результате массив.

P.S. По графику времени исполнений решений сообщества (файл 189. Runtime№2.png)
можно сделать вывод, что примерно половина решений участников совершает те самые
ненужные перестановки массива.
'''
def my_solution2(nums: list[int], k: int):
    if k == len(nums):
        return nums
    elif k > len(nums):
        k = k % len(nums)
    segm = nums[:k*-1]
    del nums[:k*-1]
    nums.extend(segm)


'''
Неверное решение, проходящее только 113 тестов из 695, так как количество 
шагов k, на которые нужно развернуть массив вправо, может быть больше длины 
массива. Этот алгоритм такого не учитывает.
'''
def my_solution1(nums: list[int], k: int):
    segm = nums[:k*-1]
    del nums[:k*-1]
    nums.extend(segm)